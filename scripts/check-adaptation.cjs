require('./lib/load-typescript.cjs');
const assert = require('node:assert/strict');
const { emptyRuntimeState, retainTrainingHistory } = require('../src/runtime/runtimePersistence.ts');
const { compileTrainingBlock, solveTrainingSession, recordRuntimeSet, commitRuntimeSession, skipRemainingRuntimeSets, previewTrainingSession, undoLastRuntimeSet } = require('../src/runtime/runtimeService.ts');
const { previewRemainingWeek, applyRemainingWeek } = require('../src/runtime/remainingWeek.ts');
const { computeWeeklyStatus } = require('../src/runtime/status.ts');
const { toStoredTraining, fromStoredTraining } = require('../src/runtime/trainingState.ts');
const source = { id:'00000000-0000-4000-8000-000000000001',userId:'00000000-0000-4000-8000-000000000002',version:1,goal:'hypertrophy',experience:'intermediate',daysPerWeek:4,sessionMinutes:60,equipment:['barbell','rack','dumbbell','bench','machine','cable','pullup_bar'],excludedExerciseIds:[],limitations:[],seedWorkingSets:[],createdAt:'2026-09-21T12:00:00Z' };
const context = {date:'2026-09-22',minutesAvailable:60,recovery:'yes',unavailableEquipment:[],unavailableExerciseIds:[]};
let state = compileTrainingBlock(emptyRuntimeState(),source);
state.block.startedOn = '2026-09-21'; // Monday missed; Tuesday workout logged.
state = solveTrainingSession(state,context);
const originalSets = structuredClone(state.activeSession.exercises[0].sets);
const entry = state.activeSession.exercises[0]; const set = entry.sets[0];
const logged = recordRuntimeSet(state,{prescriptionId:state.activeSession.id,setId:set.id,exerciseId:entry.exercise.id,prescribedLoadKg:set.loadKg,prescribedMinReps:set.minReps,prescribedMaxReps:set.maxReps,targetRir:set.targetRir,actualLoadKg:17.5,completedReps:set.maxReps,reportedRir:set.targetRir,completedAt:'2026-09-22T12:00:00Z'});
assert.deepEqual(undoLastRuntimeSet(logged).activeSession.exercises[0].sets.map(({result,decision,...s})=>s), originalSets);
state = commitRuntimeSession(skipRemainingRuntimeSets(logged));
const before = JSON.stringify(state.sessions);
const baseline = computeWeeklyStatus(state.block,state.sessions,state.setResults,1);
const windows = [{...context,date:'2026-09-23',minutesAvailable:35,unavailableEquipment:['rack']},{...context,date:'2026-09-25',minutesAvailable:30,recovery:'meh',unavailableEquipment:['rack']}];
const proposal = previewRemainingWeek(state,windows,'2026-09-23');
assert.equal(JSON.stringify(state.sessions),before,'preview must not change history');
assert.equal(state.block.remainingWeek,undefined,'preview does not apply');
assert(proposal.explanation.some(x=>x.includes('below their weekly targets')));
for (const window of proposal.plan.remainingWeek.windows) {
  assert(window.workout.estimatedMinutes <= window.minutesAvailable);
  assert(window.workout.exercises.length);
  assert(window.workout.exercises.every(x=>!x.exercise.equipment.includes('rack')));
}
let adapted = applyRemainingWeek(state,proposal);
assert.equal(JSON.stringify(adapted.sessions),before);
assert.notEqual(adapted.block.id,state.block.id);
assert.equal(adapted.block.startedOn,state.block.startedOn);
assert.equal(adapted.block.groupId,state.block.groupId);
const status = computeWeeklyStatus(adapted.block,adapted.sessions,adapted.setResults,1);
assert.deepEqual(status.muscles.map(x=>x.completedSets),baseline.muscles.map(x=>x.completedSets));
assert(status.muscles.every(x=>x.completedSets+x.scheduledSets<=x.max));
assert.equal(computeWeeklyStatus(adapted.block,adapted.sessions,adapted.setResults,2).totalSessions,4,'next week retains usual schedule');
assert.throws(()=>solveTrainingSession(adapted,{...context,date:'2026-09-24'}),/No workout planned/);
const workout = previewTrainingSession(adapted,windows[0]);
assert.deepEqual(workout.exercises.map(x=>[x.exercise.id,x.sets.length]),proposal.plan.remainingWeek.windows[0].workout.exercises.map(x=>[x.exercise.id,x.sets.length]));
const persisted = fromStoredTraining(toStoredTraining(adapted));
assert.deepEqual(persisted.block.remainingWeek,adapted.block.remainingWeek);
assert.equal(JSON.stringify(persisted.sessions),before);
const updated = retainTrainingHistory(adapted,compileTrainingBlock(adapted,{...source,version:2,sessionMinutes:45}));
assert.deepEqual(computeWeeklyStatus(updated.block,updated.sessions,updated.setResults,1).muscles.map(x=>x.completedSets),baseline.muscles.map(x=>x.completedSets));
assert.throws(()=>applyRemainingWeek(updated,proposal),/Preview|Preview|preview/);
assert.throws(()=>previewRemainingWeek(state,[windows[0],windows[0]],'2026-09-23'),/once/);
assert.throws(()=>previewRemainingWeek(state,[{...windows[0],minutesAvailable:0}],'2026-09-23'),/10–180/);
assert.throws(()=>previewRemainingWeek(state,[{...windows[0],date:'2026-09-28'}],'2026-09-23'),/remaining date/);
assert.throws(()=>previewRemainingWeek(state,[{...windows[0],unavailableEquipment:source.equipment}],'2026-09-23'),/No suitable/);
const none = applyRemainingWeek(state,previewRemainingWeek(state,[],'2026-09-23'));
assert(computeWeeklyStatus(none.block,none.sessions,none.setResults,1).muscles.every(x=>x.scheduledSets===0));
assert.throws(()=>previewRemainingWeek(solveTrainingSession(adapted,windows[0]),windows,'2026-09-23'),/active workout/);
console.log('adaptation scenario passed: missed Monday, 35-minute Wednesday, unavailable rack, immutable history, bounded workload, explicit acceptance, persistence, next-week schedule');
