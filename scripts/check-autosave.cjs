const assert=require('node:assert/strict');
const h=require('./lib/react-harness.cjs');
const {React,act,render,advance,appState,mockFile,mocks,deferred}=h;
const {emptyRuntimeState}=require('../src/runtime/runtimePersistence.ts');
const {prepareOnboardingTraining}=require('../src/runtime/onboarding.ts');
const {RUNTIME_EXERCISES}=require('../src/runtime/exerciseCatalog.ts');
mocks.set('expo-image-picker',{});
mockFile('src/services/userProfileService.ts',{uploadUserAvatar:async()=>({})});
mockFile('src/screens/runtime/WeightSettings.tsx',{useWeightSettings:()=>({unit:'kg',ranges:{},save:()=>{}})});
const {AccountSurface}=require('../src/screens/runtime/AccountSurface.tsx');
const {SavedRoutines}=require('../src/screens/runtime/SavedRoutines.tsx');
for(const name of ['RoutineContextChips','RoutineDescription','RoutineDraftReview','RoutineVoiceInput'])mockFile(`src/screens/runtime/${name}.tsx`,{[name]:name});
mockFile('src/services/routineInputService.ts',{hostedRoutineInputEnabled:false,interpretRoutine:async()=>{throw Error('not requested');}});
const {SourceIntake}=require('../src/screens/runtime/SourceIntake.tsx');
const state=prepareOnboardingTraining({...emptyRuntimeState(),catalog:RUNTIME_EXERCISES},{id:'test',trainingSplit:'upper_lower',experienceLevel:'beginner',planPreferences:{daysPerWeek:4,sessionMinutes:60,equipmentLevel:'full_gym',injuries:[]}},()=>0.4);
const user={id:'test',name:'Alex',sex:'male',experienceLevel:'beginner',age:25,heightCm:175,weightKg:70,createdAt:'2026-10-17T12:00:00Z'};
async function main(){
  const saves=[];let gate=null,fail=false;
  const props={user,state,sync:'synced',routineControls:null,onUseRoutine:()=>{},onRenameRoutine:()=>{},onLogout:()=>{},onDeleteAccount:()=>{},onSaveProfile:async value=>{saves.push(value);if(gate)await gate.promise;if(fail)throw Error('offline');}};
  let tree=await render(React.createElement(AccountSurface,props));
  const edit=()=>tree.root.findByProps({accessibilityLabel:'Edit profile'}).props.onPress();
  const change=(label,value)=>tree.root.findByProps({accessibilityLabel:label}).props.onChangeText(value);
  await act(async()=>edit());await act(async()=>change('name','Alex updated'));
  assert.equal(saves.length,0);
  await act(async()=>appState('inactive'));
  assert.equal(saves.length,1,'Background flushes before debounce');assert.equal(saves[0].name,'Alex updated');
  await act(async()=>appState('background'));await advance(600);assert.equal(saves.length,1,'Repeated lifecycle events do not duplicate saves');
  await act(async()=>appState('active'));
  gate=deferred();await act(async()=>change('name','Older edit'));await advance(600);
  await act(async()=>change('name','Newest edit'));
  await act(async()=>tree.update(React.createElement(AccountSurface,{...props,active:false})));
  await act(async()=>{gate.resolve();});gate=null;
  assert.deepEqual(saves.slice(-2).map(x=>x.name),['Older edit','Newest edit'],'Latest edit wins while prior request is in flight');
  await act(async()=>change('height','90'));await advance(600);assert.notEqual(saves.at(-1).heightCm,90,'Invalid drafts do not overwrite profile');
  await act(async()=>change('height','180'));fail=true;await advance(600);
  fail=false;await act(async()=>appState('inactive'));assert.equal(saves.at(-1).heightCm,180,'Failed autosave stays dirty and can retry');
  await act(async()=>appState('active'));await act(async()=>change('name','Final edit'));
  await act(async()=>tree.unmount());assert.equal(saves.at(-1).name,'Final edit','Unmount flushes the latest draft');

  const edits=[];
  tree=await render(React.createElement(SourceIntake,{inline:true,initial:state.source,sync:'synced',onClose:()=>{},onSave:value=>{edits.push(value);}}));
  await act(async()=>tree.root.findByType('RoutineDescription').props.onChange('Upper / lower on weekdays'));
  await act(async()=>appState('inactive'));assert.equal(edits.at(-1).text,'Upper / lower on weekdays');
  await act(async()=>appState('active'));
  await act(async()=>tree.root.findByType('RoutineDescription').props.onChange('New text before switching tabs'));
  await act(async()=>tree.unmount());assert.equal(edits.at(-1).text,'New text before switching tabs');

  const renames=[];
  const routineProps={state,onUseRoutine:()=>{throw Error('Name editing must not activate a routine');},onRenameRoutine:(id,name)=>{renames.push({id,name});},onBack:()=>{}};
  tree=await render(React.createElement(SavedRoutines,routineProps));
  const input=()=>tree.root.findAllByType('TextInput')[0];
  await act(async()=>input().props.onFocus());await act(async()=>input().props.onChangeText('My routine'));
  await act(async()=>appState('inactive'));assert.equal(renames.at(-1).name,'My routine');
  await act(async()=>input().props.onEndEditing());assert.equal(renames.length,1,'Blur after lifecycle flush saves exactly once');
  await act(async()=>appState('active'));await act(async()=>input().props.onFocus());await act(async()=>input().props.onChangeText('Tab change'));
  await act(async()=>tree.update(React.createElement(SavedRoutines,{...routineProps,active:false})));
  assert.equal(renames.at(-1).name,'Tab change');
  await act(async()=>input().props.onFocus());await act(async()=>input().props.onChangeText('Before back'));
  await act(async()=>tree.unmount());assert.equal(renames.at(-1).name,'Before back');
  assert.equal(h.listeners.size,0);
  console.log('Autosave: profile serialization, validation, failed-save retry, background/tab/unmount flush, routine text and name edits passed.');
}
main().then(()=>h.restore()).catch(e=>{h.restore();console.error(e);process.exitCode=1;});
