require('./lib/load-typescript.cjs');
const fs = require('node:fs');
const { TRAINING_SCHEMA, TRAINING_TABLES } = require('../src/runtime/dataModel.ts');
const { RUNTIME_EXERCISES } = require('../src/runtime/exerciseCatalog.ts');
const { validateCatalog } = require('../src/runtime/catalogValidation.ts');
const catalog = validateCatalog(RUNTIME_EXERCISES);
const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;
const sql = '-- Generated by node scripts/seed-exercises.cjs. Stable IDs match the bundled offline catalog.\n'
  + `insert into ${TRAINING_SCHEMA}.${TRAINING_TABLES.exercises}(id,source,source_id,source_url,license,status,definition) values\n`
  + catalog.map((entry) => `(${quote(entry.id)},'fitarc',${quote(entry.id)},'fitarc://bundled-catalog','Internal FitArc metadata','approved',${quote(JSON.stringify(entry))}::jsonb)`).join(',\n')
  + '\non conflict(id) do nothing;\n';
const target = 'supabase/migrations/202609240002_seed_exercise_catalog.sql';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== sql) throw new Error('Bundled and database seed catalogs differ. Run npm run catalog:seed.');
  console.log('Database and offline seed catalogs match.');
} else { fs.writeFileSync(target, sql); console.log(`Wrote ${catalog.length} exercises to ${target}`); }
