require('./lib/load-typescript.cjs');
const assert=require('node:assert/strict');
const {prepareOnboardingTraining}=require('../src/runtime/onboarding.ts');
const {emptyRuntimeState}=require('../src/runtime/runtimePersistence.ts');
const {RUNTIME_EXERCISES}=require('../src/runtime/exerciseCatalog.ts');
const {compileTrainingBlock,solveTrainingSession,recordRuntimeSet,commitRuntimeSession,skipRemainingRuntimeSets}=require('../src/runtime/runtimeService.ts');
const {removeSessionExercise}=require('../src/runtime/removeExercise.ts');
const {useSavedRoutine,savedRoutines,renameSavedRoutine,routineName}=require('../src/runtime/savedRoutines.ts');
const {fromStoredTraining,toStoredTraining}=require('../src/runtime/trainingState.ts');
const {localDate}=require('../src/runtime/planDates.ts');
const context={date:localDate(),minutesAvailable:60,recovery:'yes',unavailableEquipment:[],unavailableExerciseIds:[]};
let state=prepareOnboardingTraining({...emptyRuntimeState(),catalog:RUNTIME_EXERCISES},{id:'test',trainingSplit:'upper_lower',experienceLevel:'beginner',planPreferences:{daysPerWeek:4,sessionMinutes:60,equipmentLevel:'full_gym',injuries:[]}},()=>0.4);
const original=JSON.parse(JSON.stringify(state.block));
state=solveTrainingSession(state,context);
const removed=state.activeSession.exercises.at(-1).id;
state=removeSessionExercise(state,removed);
const entries=state.activeSession.exercises.map(entry=>entry.exercise.id);
const entry=state.activeSession.exercises[0],set=entry.sets[0];
state=recordRuntimeSet(state,{prescriptionId:state.activeSession.id,setId:set.id,exerciseId:entry.exercise.id,prescribedLoadKg:set.loadKg,actualLoadKg:30,prescribedMinReps:set.minReps,prescribedMaxReps:set.maxReps,targetRir:set.targetRir,completedReps:10,reportedRir:2,completedAt:new Date().toISOString()});
state=commitRuntimeSession(skipRemainingRuntimeSets(state));
assert.equal(state.block.id,original.id,'Ordinary completion preserves the queue revision');
assert.deepEqual(state.block,original,'Queue contents are not replaced by the selected batch');
// An explicit edit, not completion, creates a different saved routine.
state={...compileTrainingBlock(state,{...state.source,version:state.source.version+1,routine:{...state.source.routine,workouts:state.source.routine.workouts.map(w=>w.id===state.sessions[0].slotId?{...w,exercises:w.exercises.filter(e=>entries.includes(e.exerciseId))}:w)}}),blockHistory:[original]};
assert.notEqual(state.block.id,original.id);
const workout=state.source.routine.workouts.find(w=>w.id===state.sessions[0].slotId);
assert.equal(workout.reuseSelection,undefined);
assert.deepEqual(workout.exercises.map(e=>e.exerciseId),entries);
const stored=toStoredTraining(state);
assert(!('preferences' in stored));assert(!('routine' in stored.profile));assert(!JSON.stringify(stored).includes('routineEditor'));
state=fromStoredTraining(JSON.parse(JSON.stringify(stored)));
const oldSessions=JSON.stringify(state.sessions),oldResults=JSON.stringify(state.setResults);
const restored=useSavedRoutine(state,original.id);
assert.equal(restored.block.id,state.block.id,'Selecting an older revision resolves to the current style');
assert.equal(JSON.stringify(restored.sessions),oldSessions);
assert.equal(JSON.stringify(restored.setResults),oldResults);
assert.deepEqual(restored.source.routine.workouts.map(w=>w.exercises.map(e=>e.exerciseId)),state.block.slots.map(slot=>slot.plannedExercises.map(e=>e.exerciseId)));
const ongoing=solveTrainingSession(state,context);
assert.equal(useSavedRoutine(ongoing,original.id),ongoing,'Selecting the current style during a workout is a no-op');
assert.equal(JSON.stringify(state.sessions),oldSessions);
const slot=state.block.slots.find(s=>s.id===workout.id);
const {selectPoolPlans}=require('../src/runtime/exercisePools.ts');
assert.deepEqual(selectPoolPlans(slot,state.source,state.block.catalog,context,state.sessions).map(p=>p.exerciseId),entries);
console.log('Routine reuse passed: versioned choices, explicit queue edits, unchanged history, restore, serialization, active-workout guards.');

const {upgradeStoredTraining}=require('../src/runtime/upgradeStoredTraining.ts');
const legacy=JSON.parse(JSON.stringify({...stored,schemaVersion:3,preferences:{...state.source,routineEditor:{text:'My routine',interpretedText:'Upper lower',draft:{preferredSplit:'upper_lower'}}}}));
delete legacy.profile;
legacy.plans=legacy.plans.map(plan=>({...plan,preferences:{...plan.preferences,routineEditor:{text:'obsolete editor copy'}}}));
const legacyBefore=JSON.stringify(legacy);
const upgraded=upgradeStoredTraining(legacy);
assert.equal(upgraded.schemaVersion,4);
assert.equal(upgraded.profile.routineText,'My routine');
assert.equal(upgraded.profile.interpretedRoutineText,'Upper lower');
assert.equal(upgraded.profile.trainingSplit,'upper_lower');
assert(!JSON.stringify(upgraded).includes('routineEditor'));
assert(!('routine' in upgraded.profile));
assert.deepEqual(upgraded.sessions,stored.sessions);
assert.deepEqual(fromStoredTraining(upgraded).source.routine,state.source.routine);
assert.equal(JSON.stringify(legacy),legacyBefore,'Upgrade must not mutate the old device backup');
assert.equal(upgradeStoredTraining(stored),stored,'Current device data needs no upgrade');
console.log('Device v3 upgrade passed: text, selected split, routine, session history, immutable backup, v4 passthrough.');

const duplicates={...state,blockHistory:[...state.blockHistory,{...state.block,id:'duplicate-routine',version:999}]};
const routines=savedRoutines(duplicates);
assert.equal(routines[0].id,state.block.id,'Current routine stays first');
assert(!routines.some(plan=>plan.id==='duplicate-routine'),'Identical revisions are hidden');
assert(!routines.some(plan=>plan.id===original.id),'Older exercise choices are revisions of the same style');
assert.equal(routines.length,1);
console.log('Saved routines: one entry per style, current first, older revisions preserved outside the selector.');

const beforeRename=JSON.stringify(state);
const renamed=renameSavedRoutine(state,state.block.id,'  My gym routine  ');
assert.equal(routineName(renamed.block),'My gym routine');
assert.deepEqual(renamed.block.slots,state.block.slots);
assert.deepEqual(renamed.sessions,state.sessions);
assert.deepEqual(renamed.blockHistory.find(plan=>plan.id===state.block.id),state.block);
assert.equal(savedRoutines(renamed).length,savedRoutines(state).length,'Renaming does not add a duplicate card');
const reloaded=fromStoredTraining(JSON.parse(JSON.stringify(toStoredTraining(renamed))));
assert.equal(routineName(reloaded.block),'My gym routine');
assert.equal(reloaded.source.routine.name,'My gym routine');
assert.equal(useSavedRoutine(reloaded,reloaded.block.id).source.routine.name,'My gym routine');
const other=prepareOnboardingTraining({...emptyRuntimeState(),catalog:RUNTIME_EXERCISES},{id:'test',trainingSplit:'full_body',experienceLevel:'beginner',planPreferences:{daysPerWeek:4,sessionMinutes:60,equipmentLevel:'full_gym',injuries:[]}},()=>0.4).block;
const renamedOther=renameSavedRoutine({...reloaded,blockHistory:[...reloaded.blockHistory,other]},other.id,'Home routine');
assert.equal(renamedOther.block.id,reloaded.block.id,'Renaming an inactive routine must not activate it');
assert(savedRoutines(renamedOther).some(plan=>routineName(plan)==='Home routine'));
assert.throws(()=>renameSavedRoutine(state,state.block.id,'  '),/name/);
assert.throws(()=>renameSavedRoutine(state,state.block.id,'x'.repeat(81)),/name/);
assert.equal(renameSavedRoutine(renamed,renamed.block.id,'My gym routine'),renamed,'Unchanged name is a no-op');
assert.throws(()=>renameSavedRoutine(solveTrainingSession(state,context),state.block.id,'New name'),/Finish/);
assert.equal(JSON.stringify(state),beforeRename,'Name edits must not mutate input/history');
console.log('Routine names: active/inactive rename, no duplicate cards, immutable history, persistence, switching and validation passed.');

// Style switches restore independent queues and the next group, including after restart.
const {previewTrainingSession}=require('../src/runtime/runtimeService.ts');
const {styleSessionCount}=require('../src/runtime/trainingStyles.ts');
const {saveRoutineEditor}=require('../src/routineSetup/editor.ts');
const {draftFromRoutine}=require('../src/routineSetup/draft.ts');
const {groupDraft}=require('../src/routineSetup/pools.ts');
let switching={...state,block:original,source:original.preferences,blockHistory:[original,other]};
const expected=previewTrainingSession(switching,context);
assert.equal(expected.slotId,original.slots[1].id,'Upper completion leaves Lower next');
const originalHistory=JSON.stringify(switching.sessions);
switching=useSavedRoutine(switching,other.id);
assert.equal(savedRoutines(switching).length,2);
assert.equal(styleSessionCount(switching,original),1);
assert.equal(styleSessionCount(switching,switching.block),0);
switching=fromStoredTraining(JSON.parse(JSON.stringify(toStoredTraining(switching))));
switching=useSavedRoutine(switching,original.id);
assert.equal(previewTrainingSession(switching,context).slotId,expected.slotId);
assert.deepEqual(previewTrainingSession(switching,context).exercises.map(e=>e.exercise.id),expected.exercises.map(e=>e.exercise.id));
assert.equal(JSON.stringify(switching.sessions),originalHistory);
assert.equal(savedRoutines(switching).length,2,'Activation adds no extra style cards');
// The Profile style selector must also restore saved choices rather than regroup current choices.
switching=useSavedRoutine(switching,other.id);
const grouped=groupDraft(draftFromRoutine(switching.source.routine,switching.source,RUNTIME_EXERCISES),'upper_lower',RUNTIME_EXERCISES);
switching=saveRoutineEditor(switching,{text:'',interpretedText:'',draft:grouped,settings:switching.source},RUNTIME_EXERCISES);
assert.deepEqual(switching.block.slots.map(s=>s.plannedExercises.map(e=>e.exerciseId)),original.slots.map(s=>s.plannedExercises.map(e=>e.exerciseId)));
assert.equal(previewTrainingSession(switching,context).slotId,expected.slotId);
assert.equal(savedRoutines(switching).length,2);
assert.equal(styleSessionCount(switching,switching.block),1);
console.log('Training styles: independent queues, resumed group, one card per style, profile switching, session counts and restart passed.');

// Switching styles must preserve the in-progress occurrence and all recorded sets.
let inProgress=solveTrainingSession({...state,block:original,source:original.preferences,blockHistory:[original,other]},context);
const pending=inProgress.activeSession, firstEntry=pending.exercises[0], firstSet=firstEntry.sets[0];
inProgress=recordRuntimeSet(inProgress,{prescriptionId:pending.id,setId:firstSet.id,exerciseId:firstEntry.exercise.id,prescribedLoadKg:firstSet.loadKg,actualLoadKg:25,prescribedMinReps:firstSet.minReps,prescribedMaxReps:firstSet.maxReps,targetRir:firstSet.targetRir,completedReps:10,reportedRir:2,completedAt:new Date().toISOString()});
const snapshot=JSON.stringify(inProgress.activeSession), results=JSON.stringify(inProgress.setResults);
let switched=useSavedRoutine(inProgress,other.id);
assert.equal(switched.source.trainingSplit,'full_body');
assert.equal(switched.activeSession,null,'Switch shows the new style immediately');
assert.equal(switched.sessions.find(s=>s.id===pending.id).status,'paused');
assert.equal(JSON.stringify(switched.setResults),results);
switched=fromStoredTraining(JSON.parse(JSON.stringify(toStoredTraining(switched))));
assert.equal(switched.activeSession,null,'Restart must not activate another style’s paused workout');
switched=useSavedRoutine(switched,original.id);
assert.equal(switched.activeSession.id,pending.id);
assert.deepEqual(switched.activeSession.exercises,JSON.parse(snapshot).exercises);
switched=commitRuntimeSession(skipRemainingRuntimeSets(switched));
assert.equal(switched.source.trainingSplit,'upper_lower');
switched=useSavedRoutine(switched,other.id);
assert.equal(styleSessionCount(switched,other),0,'Old workout is not attributed to the newly selected style');
assert.equal(styleSessionCount(switched,original),2);
assert.equal(previewTrainingSession(switched,context).slotId,other.slots[0].id,'The new style starts with its own queue');
assert.equal(previewTrainingSession(useSavedRoutine(switched,original.id),context).slotId,original.slots[0].id,'The old style advanced only when its workout completed');
console.log('Active style switching: recorded work, restart, completion ownership and independent queue continuation passed.');
