require('./lib/load-typescript.cjs');
const assert=require('node:assert/strict');
const {prepareOnboardingTraining}=require('../src/runtime/onboarding.ts');
const {emptyRuntimeState}=require('../src/runtime/runtimePersistence.ts');
const {RUNTIME_EXERCISES}=require('../src/runtime/exerciseCatalog.ts');
const {solveTrainingSession,recordRuntimeSet,commitRuntimeSession,skipRemainingRuntimeSets}=require('../src/runtime/runtimeService.ts');
const {removeSessionExercise}=require('../src/runtime/removeExercise.ts');
const {useSavedRoutine,savedRoutines}=require('../src/runtime/savedRoutines.ts');
const {fromStoredTraining,toStoredTraining}=require('../src/runtime/trainingState.ts');
const {localDate}=require('../src/runtime/planDates.ts');
const context={date:localDate(),minutesAvailable:60,recovery:'yes',unavailableEquipment:[],unavailableExerciseIds:[]};
let state=prepareOnboardingTraining({...emptyRuntimeState(),catalog:RUNTIME_EXERCISES},{id:'test',trainingSplit:'upper_lower',experienceLevel:'beginner',planPreferences:{daysPerWeek:4,sessionMinutes:60,equipmentLevel:'full_gym',injuries:[]}},()=>0.4);
const original=JSON.parse(JSON.stringify(state.block));
state=solveTrainingSession(state,context);
const removed=state.activeSession.exercises.at(-1).id;
state=removeSessionExercise(state,removed);
const entries=state.activeSession.exercises.map(entry=>entry.exercise.id);
const entry=state.activeSession.exercises[0],set=entry.sets[0];
state=recordRuntimeSet(state,{prescriptionId:state.activeSession.id,setId:set.id,exerciseId:entry.exercise.id,prescribedLoadKg:set.loadKg,actualLoadKg:30,prescribedMinReps:set.minReps,prescribedMaxReps:set.maxReps,targetRir:set.targetRir,completedReps:10,reportedRir:2,completedAt:new Date().toISOString()});
state=commitRuntimeSession(skipRemainingRuntimeSets(state));
assert.notEqual(state.block.id,original.id);
assert.deepEqual(state.blockHistory.find(p=>p.id===original.id),original);
const workout=state.source.routine.workouts.find(w=>w.id===state.sessions[0].slotId);
assert.equal(workout.reuseSelection,true);
assert.deepEqual(workout.exercises.map(e=>e.exerciseId),entries);
const stored=toStoredTraining(state);
assert(!('preferences' in stored));assert(!('routine' in stored.profile));assert(!JSON.stringify(stored).includes('routineEditor'));
state=fromStoredTraining(JSON.parse(JSON.stringify(stored)));
const oldSessions=JSON.stringify(state.sessions),oldResults=JSON.stringify(state.setResults);
const restored=useSavedRoutine(state,original.id);
assert.notEqual(restored.block.id,original.id);
assert.equal(JSON.stringify(restored.sessions),oldSessions);
assert.equal(JSON.stringify(restored.setResults),oldResults);
assert.deepEqual(restored.source.routine.workouts.map(w=>w.exercises.map(e=>e.exerciseId)),original.slots.map(slot=>slot.plannedExercises.map(e=>e.exerciseId)));
assert.throws(()=>useSavedRoutine(solveTrainingSession(state,context),original.id),/Finish/);
assert.equal(JSON.stringify(state.sessions),oldSessions);
const slot=state.block.slots.find(s=>s.id===workout.id);
const {selectPoolPlans}=require('../src/runtime/exercisePools.ts');
assert.deepEqual(selectPoolPlans(slot,state.source,state.block.catalog,context,state.sessions).map(p=>p.exerciseId),entries);
console.log('Routine reuse passed: versioned choices, removal reuse, unchanged history, restore, serialization, active-workout guards.');

const {upgradeStoredTraining}=require('../src/runtime/upgradeStoredTraining.ts');
const legacy=JSON.parse(JSON.stringify({...stored,schemaVersion:3,preferences:{...state.source,routineEditor:{text:'My routine',interpretedText:'Upper lower',draft:{preferredSplit:'upper_lower'}}}}));
delete legacy.profile;
legacy.plans=legacy.plans.map(plan=>({...plan,preferences:{...plan.preferences,routineEditor:{text:'obsolete editor copy'}}}));
const legacyBefore=JSON.stringify(legacy);
const upgraded=upgradeStoredTraining(legacy);
assert.equal(upgraded.schemaVersion,4);
assert.equal(upgraded.profile.routineText,'My routine');
assert.equal(upgraded.profile.interpretedRoutineText,'Upper lower');
assert.equal(upgraded.profile.trainingSplit,'upper_lower');
assert(!JSON.stringify(upgraded).includes('routineEditor'));
assert(!('routine' in upgraded.profile));
assert.deepEqual(upgraded.sessions,stored.sessions);
assert.deepEqual(fromStoredTraining(upgraded).source.routine,state.source.routine);
assert.equal(JSON.stringify(legacy),legacyBefore,'Upgrade must not mutate the old device backup');
assert.equal(upgradeStoredTraining(stored),stored,'Current device data needs no upgrade');
console.log('Device v3 upgrade passed: text, selected split, routine, session history, immutable backup, v4 passthrough.');

const duplicates={...state,blockHistory:[...state.blockHistory,{...state.block,id:'duplicate-routine',version:999}]};
const routines=savedRoutines(duplicates);
assert.equal(routines[0].id,state.block.id,'Current routine stays first');
assert(!routines.some(plan=>plan.id==='duplicate-routine'),'Identical revisions are hidden');
assert(routines.some(plan=>plan.id===original.id),'Different exercise choices remain available');
console.log('Saved routines: current first, identical revisions hidden, distinct exercise selections retained.');
