require('./lib/load-typescript.cjs');
const assert=require('node:assert/strict');
const {prepareOnboardingTraining}=require('../src/runtime/onboarding.ts');
const {emptyRuntimeState}=require('../src/runtime/runtimePersistence.ts');
const {RUNTIME_EXERCISES}=require('../src/runtime/exerciseCatalog.ts');
const {solveTrainingSession,recordRuntimeSet}=require('../src/runtime/runtimeService.ts');
const {removeSessionExercise,restoreSessionExercise}=require('../src/runtime/removeExercise.ts');
const {toStoredTraining,fromStoredTraining}=require('../src/runtime/trainingState.ts');
const {localDate}=require('../src/runtime/planDates.ts');
let state=prepareOnboardingTraining({...emptyRuntimeState(),catalog:RUNTIME_EXERCISES},{id:'test',trainingSplit:'upper_lower',experienceLevel:'beginner',planPreferences:{daysPerWeek:4,sessionMinutes:60,equipmentLevel:'full_gym',injuries:[]}},()=>0.4);
state=solveTrainingSession(state,{date:localDate(),minutesAvailable:60,recovery:'yes',unavailableEquipment:[],unavailableExerciseIds:[]});
const log=(state,index)=>{const s=state.activeSession,e=s.exercises[index],set=e.sets[0];return recordRuntimeSet(state,{prescriptionId:s.id,setId:set.id,exerciseId:e.exercise.id,prescribedLoadKg:set.loadKg,actualLoadKg:30,prescribedMinReps:set.minReps,prescribedMaxReps:set.maxReps,targetRir:set.targetRir,completedReps:10,reportedRir:2,completedAt:new Date().toISOString()});};
state=log(state,0);
const saved={sessionId:state.activeSession.id,index:0,entry:state.activeSession.exercises[0]};
let removed=removeSessionExercise(state,saved.entry.id);
assert.equal(removed.setResults.length,0);assert.equal(state.setResults.length,1);
assert(!removed.workingSets[saved.entry.exercise.id]);
assert.deepEqual(removed.source,state.source);assert.deepEqual(removed.block,state.block);
removed=log(removed,0);
const restored=restoreSessionExercise(removed,saved);
assert.equal(restored.setResults.length,2,'Undo retains new sets on other exercises');
assert.deepEqual(restored.activeSession.exercises[0],saved.entry);
assert.throws(()=>restoreSessionExercise(restored,saved),/already/);
assert.throws(()=>restoreSessionExercise({...removed,activeSession:null},saved),/ended/);
assert.deepEqual(fromStoredTraining(toStoredTraining(removed)).setResults,removed.setResults);
let empty=removed;for(const e of removed.activeSession.exercises)empty=removeSessionExercise(empty,e.id);
assert.equal(empty.activeSession.exercises.length,0);assert.equal(empty.setResults.length,0);
assert.equal(restoreSessionExercise(empty,saved).activeSession.exercises.length,1);
console.log('Exercise deletion passed: logged/unlogged removal, projections, persistence, last card, Undo preserves other edits, stale/duplicate Undo guards.');
