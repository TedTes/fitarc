require('./lib/load-typescript.cjs');
const assert=require('node:assert/strict');
const {emptyRuntimeState}=require('../src/runtime/runtimePersistence.ts');
const {prepareOnboardingTraining}=require('../src/runtime/onboarding.ts');
const {selectTrainingStyle,jumpTrainingGroup}=require('../src/runtime/planActions.ts');
const {proposeGoalChange,applyGoalChange,GOAL_DEFAULTS}=require('../src/runtime/goalChanges.ts');
const {savedRoutines}=require('../src/runtime/savedRoutines.ts');
const {recordRuntimeSet,commitRuntimeSession,skipRemainingRuntimeSets,previewTrainingSession}=require('../src/runtime/runtimeService.ts');
const {startAdditionalWorkout}=require('../src/runtime/freeWorkout.ts');
const {fromStoredTraining,toStoredTraining}=require('../src/runtime/trainingState.ts');
const {logConditioning,goalProgress}=require('../src/runtime/goalProgress.ts');
const {localDate,datePlusDays}=require('../src/runtime/planDates.ts');
const {weightText,rangeLoad,toKg}=require('../src/runtime/weights.ts');
const {computeWeeklyStatus}=require('../src/runtime/status.ts');
const {RUNTIME_EXERCISES}=require('../src/runtime/exerciseCatalog.ts');
let state=prepareOnboardingTraining({...emptyRuntimeState(),catalog:RUNTIME_EXERCISES},{id:'tester',trainingSplit:'upper_lower',experienceLevel:'beginner',planPreferences:{daysPerWeek:4,sessionMinutes:45,equipmentLevel:'full_gym',injuries:[]}},()=>0.4);
const defaults=state.source,upper=state.block.slots[0].id;
state=jumpTrainingGroup(state,upper);
function log(s){const e=s.activeSession.exercises[0],set=e.sets.find(x=>x.status==='pending');return recordRuntimeSet(s,{prescriptionId:s.activeSession.id,setId:set.id,exerciseId:e.exercise.id,prescribedLoadKg:set.loadKg,actualLoadKg:20,prescribedMinReps:set.minReps,prescribedMaxReps:set.maxReps,targetRir:set.targetRir,completedReps:10,reportedRir:2,completedAt:new Date().toISOString()});}
state=log(state);
const session=structuredClone(state.activeSession);
state=selectTrainingStyle(state,defaults,'push_pull_legs');
assert.equal(state.activeSession,null);
assert.equal(state.sessions.find(s=>s.id===session.id).status,'paused');
state=jumpTrainingGroup(state,state.block.slots[0].id);
const push=state.activeSession.id;
state=selectTrainingStyle(state,defaults,'upper_lower');
assert.equal(state.activeSession.id,session.id);
assert.equal(state.sessions.find(s=>s.id===push).status,'paused');
state=fromStoredTraining(JSON.parse(JSON.stringify(toStoredTraining(state))));
assert.equal(state.activeSession.id,session.id);
const before=JSON.stringify(state);
const proposal=proposeGoalChange(state,defaults,'strength',true);
assert(proposal.changes.some(c=>c.includes('reps')));
assert(proposal.changes.some(c=>c.includes('rest')));
assert.equal(JSON.stringify(state),before,'Review and cancellation have no side effects');
const preserved=applyGoalChange(state,defaults,proposeGoalChange(state,defaults,'strength',false));
assert.equal(JSON.stringify(preserved.block.slots.map(s=>s.plannedExercises.map(e=>e.prescription))),JSON.stringify(state.block.slots.map(s=>s.plannedExercises.map(e=>e.prescription))),'No opt-in means user targets are preserved');
state=applyGoalChange(state,defaults,proposal);
assert.deepEqual(state.activeSession.exercises,JSON.parse(before).activeSession.exercises,'Goal changes do not alter an open workout');
for(const p of savedRoutines(state)){assert.equal(p.goal,'strength');for(const slot of p.slots)for(const e of slot.plannedExercises)assert.equal(e.prescription.maxReps,8);}
assert.throws(()=>applyGoalChange(state,defaults,proposal),/Review/,'Stale review cannot overwrite newer edits');
state=commitRuntimeSession(skipRemainingRuntimeSets(state));
const queues=JSON.stringify(savedRoutines(state).map(p=>p.slots));
const history=state.sessions.length;
const next=previewTrainingSession(state,{date:datePlusDays(localDate(),1),minutesAvailable:45,recovery:'yes',unavailableEquipment:[],unavailableExerciseIds:[]});
state=startAdditionalWorkout(state,defaults,[{exerciseId:'bench_press',sets:1,minReps:8,maxReps:12,targetRir:2}],'Freestyle');
assert.equal(state.activeSession.blockId,null);
assert(!state.activeSession.exerciseQueue);
state=commitRuntimeSession(skipRemainingRuntimeSets(log(state)));
assert.equal(JSON.stringify(savedRoutines(state).map(p=>p.slots)),queues);
assert.equal(state.sessions.length,history+1);
assert.equal(previewTrainingSession(state,{date:datePlusDays(localDate(),1),minutesAvailable:45,recovery:'yes',unavailableEquipment:[],unavailableExerciseIds:[]}).slotId,next.slotId);
const coverage=computeWeeklyStatus(state.block,state.sessions,state.setResults);
assert(coverage.muscles.find(m=>m.muscle==='chest').completedSets>0,'Freestyle contributes to coverage');
state=logConditioning(state,25);
assert.equal(goalProgress(state,localDate(),datePlusDays(localDate(),1)).conditioningMinutes,25);
for(const goal of Object.keys(GOAL_DEFAULTS)){
 let initial=applyGoalChange(emptyRuntimeState(),defaults,proposeGoalChange(emptyRuntimeState(),defaults,goal));
 initial=selectTrainingStyle(initial,defaults,'full_body');
 assert.equal(initial.source.goal,goal);
 assert.equal(initial.block.slots[0].plannedExercises[0].prescription.maxReps,GOAL_DEFAULTS[goal].maxReps);
}
assert.equal(weightText(77,'lb'),'170');
assert.equal(rangeLoad({minKg:10,maxKg:20,stepKg:2.5},1,4),12.5);
assert.equal(weightText(rangeLoad({minKg:toKg(20,'lb'),maxKg:toKg(30,'lb'),stepKg:toKg(5,'lb')},1,3),'lb'),'25');
console.log('Plan workflow: pause/resume, independent style queues, restart, goal review/opt-in/staleness, all-style updates, freestyle coverage, conditioning and rounded increments passed.');
